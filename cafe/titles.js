// 제목 후보를 레퍼런스 글 형식으로 만든다. (AI 없이 규칙으로 — 빠르고 매번 같은 결과)
//
// 레퍼런스에서 확인한 형식
//   공사중  [공덕 리모델링] 서울 마포구 래미안공덕3차 32평의 공사중 현장입니다!
//           대전 중구 문화동 센트럴파크2단지 34평의 리모델링 공사중 현장은?
//   공사전  [마포구 리모델링] 서울 공덕동 신공덕3차삼성래미안아파트 24평 공사 전 모습 함께 살펴보기~
//           [남천동 리모델링] 부산 수영구 남천코오롱하늘채골든비치 55평 대형 평수 공사 전 모습 구조와 함께 살펴보기~
const { normRegion } = require('./boards');
const { 동표기 } = require('./names');

function 평숫자(평수) {
  const n = String(평수 || '').replace(/[^\d.]/g, '');
  return n ? `${n}평` : '';
}

function 후보({ 분류, 시도, 구, 동, 아파트명, 평수 }) {
  const 도 = normRegion(시도);
  const 평 = 평숫자(평수);
  const 동명 = String(동 || '').trim();
  const 구명 = String(구 || '').trim();
  // 대괄호 안 지역명 — 동이 있으면 동, 없으면 구
  const 동또는구 = 동명 || 구명;
  const 아파트 = String(아파트명 || '').trim();
  const 위치 = [도, 구명].filter(Boolean).join(' '); // 서울 마포구
  // 아파트명이 이미 동 이름으로 시작하면 위치에서는 동을 뺀다 (부곡동 + 부곡동푸르지오 → 겹침). 대괄호 키워드·태그는 그대로 쓴다.
  const 동위치 = 동표기({ 동: 동명, 아파트명 });
  const 위치동 = [도, 구명, 동위치].filter(Boolean).join(' '); // 서울 마포구 공덕동
  const 대형 = Number(String(평수).replace(/[^\d.]/g, '')) >= 50;

  const 단지평 = [아파트, 평].filter(Boolean).join(' ');
  const out = [];
  if (분류 === 'during') {
    out.push(`[${동또는구} 리모델링] ${위치} ${단지평}의 공사중 현장입니다!`);
    out.push(`${위치동} ${단지평}의 리모델링 공사중 현장은?`);
    out.push(`[${구명 || 동또는구} 리모델링] ${도} ${동위치 || 구명} ${단지평} 공사중 현장 함께 살펴보기~`);
  } else {
    out.push(`[${구명 || 동또는구} 리모델링] ${도} ${동위치 || 구명} ${단지평} 공사 전 모습 함께 살펴보기~`);
    out.push(
      `[${동또는구} 리모델링] ${위치} ${단지평}${대형 ? ' 대형 평수' : ''} 공사 전 모습 구조와 함께 살펴보기~`
    );
    out.push(`${위치동} ${단지평}의 리모델링 공사 전 현장은?`);
  }
  // 빈 값 때문에 생긴 공백·대괄호 정리
  return out.map((t) => t.replace(/\[\s*리모델링\]\s*/, '').replace(/\s{2,}/g, ' ').trim());
}

module.exports = { 후보 };
