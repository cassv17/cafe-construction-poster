// 이름 정리 — 위치와 아파트명이 같은 동 이름을 두 번 말하지 않게 한다.
//
// 예) 동 "부곡동" + 아파트명 "부곡동푸르지오" → "부산 금정구 부곡동 부곡동푸르지오" 로 겹친다.
//     아파트명은 그대로 두고 위치에서 동을 뺀다 → "부산 금정구 부곡동푸르지오".
//     "구서SK뷰"(동 "구서동")처럼 동 이름 앞부분만 겹쳐도 같게 본다.

/** 동 → 비교용 앞부분. 부곡동 → 부곡, 구서동 → 구서 (두 글자 미만이면 비교하지 않는다) */
function 동줄기(동) {
  return String(동 || '').trim().replace(/(동|가|리|읍|면)$/, '');
}

/** 아파트명이 이 동 이름으로 시작하면 true */
function 겹침(동, 아파트명) {
  const stem = 동줄기(동);
  return stem.length >= 2 && String(아파트명 || '').replace(/\s+/g, '').startsWith(stem);
}

/** 위치에 쓸 동. 겹치면 빈 문자열. */
function 동표기({ 동, 아파트명 }) {
  const d = String(동 || '').trim();
  return d && !겹침(d, 아파트명) ? d : '';
}

module.exports = { 겹침, 동표기 };
